package app.finance.core.model

/**
 * Раздел учёта потоков: расходы и доходы хранятся в одной таблице `category_month`
 * и различаются этим полем (SPEC.md §6). Активы — отдельный мир остатков, поэтому
 * здесь их нет.
 */
enum class LedgerSection {
    EXPENSE,
    INCOME,
}

/**
 * Секция категории. Категории скоупнуты по секции: у расходов, доходов и активов
 * свои независимые наборы (SPEC.md §1, требование продукта).
 */
enum class CategorySection {
    EXPENSE,
    INCOME,
    ASSET,
    ;

    /** true для секций, которые участвуют в потоковом учёте (расходы и доходы). */
    val isLedger: Boolean get() = this != ASSET

    fun toLedgerSection(): LedgerSection = when (this) {
        EXPENSE -> LedgerSection.EXPENSE
        INCOME -> LedgerSection.INCOME
        ASSET -> error("Секция ASSET не является потоковой: у активов свои сущности")
    }

    companion object {
        fun of(section: LedgerSection): CategorySection = when (section) {
            LedgerSection.EXPENSE -> EXPENSE
            LedgerSection.INCOME -> INCOME
        }
    }
}

/**
 * Как формируется баланс счетов категории активов (SPEC.md F4.6, D-20).
 *
 * Признак живёт в категории, а не в типе счёта: закрытый перечень типов лишь дублировал
 * названия категорий, а правило ведения баланса пользователь выбирает сам и хочет одно
 * на все счета категории. Три значения, а не «есть процент / нет», потому что процент
 * бывает известен (вклад) и неизвестен (акции, паи) — и это разные сценарии перехода
 * месяца.
 *
 * Отдельного «типа счёта» в модели больше нет (D-22): всё, что определял тип — правило
 * баланса и право на отрицательный остаток, — задаёт категория.
 */
enum class AssetBalancePolicy {
    /**
     * Доходность известна: ставка и срок задаются у счёта, баланс следующих месяцев
     * определяется расписанием вклада (F4.4).
     */
    FIXED_RATE,

    /**
     * Доходность неоднозначна (акции, паи, валюта, крипта): стоимость переносится
     * с прошлого месяца и требует подтверждения пользователем.
     */
    MANUAL_VALUATION,

    /** Роста нет (наличные, «под матрасом»): остаток переносится как есть. */
    FLAT,
    ;

    /** У категории есть доходность — известная или оцениваемая вручную. */
    val hasInterest: Boolean get() = this != FLAT

    /** Баланс месяца определяется расписанием, а не вводом пользователя. */
    val isProjected: Boolean get() = this == FIXED_RATE

    /** Стоимость нужно подтверждать вручную: перенос создаёт черновик, а не истину. */
    val needsConfirmation: Boolean get() = this == MANUAL_VALUATION

    companion object {
        /** Значение по умолчанию для категории без явного правила. */
        val DEFAULT: AssetBalancePolicy get() = FLAT
    }
}
